from collections.abc import Iterable
from pathlib import Path, PurePosixPath

import pytest

from codeindex.repository.discovery import (
    discover_files,
    summarize_discovery,
)
from codeindex.repository.models import (
    DiscoveredFile,
    Repository,
    SkipReason,
    SkippedFile,
    TrackedFile,
)


def tracked(
    path: str,
    *,
    mode: str = "100644",
    stage: int = 0,
) -> TrackedFile:
    return TrackedFile(PurePosixPath(path), mode, stage)


def discover(
    root: Path,
    entries: Iterable[TrackedFile],
    **kwargs: object,
) -> list[DiscoveredFile | SkippedFile]:
    return list(
        discover_files(
            Repository(root=root),
            tracked_files_lookup=lambda repository_root: entries,
            **kwargs,
        )
    )


def write(root: Path, relative_path: str, content: bytes) -> Path:
    path = root / relative_path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)
    return path


def test_accepts_current_utf8_working_tree_content(tmp_path: Path) -> None:
    write(tmp_path, "src/app.py", b"\xef\xbb\xbfprint('modified')\n")

    decisions = discover(tmp_path, [tracked("src/app.py")])

    assert decisions == [
        DiscoveredFile(
            relative_path=PurePosixPath("src/app.py"),
            text="print('modified')\n",
            size_bytes=21,
        )
    ]


@pytest.mark.parametrize(
    ("entry", "reason"),
    [
        (tracked("deleted.py"), SkipReason.DELETED),
        (tracked("link.py", mode="120000"), SkipReason.SYMLINK),
        (tracked("module", mode="160000"), SkipReason.SUBMODULE),
        (tracked("conflict.py", stage=2), SkipReason.UNMERGED),
        (tracked("special.py", mode="100600"), SkipReason.UNSUPPORTED_GIT_ENTRY),
        (tracked("../outside.py"), SkipReason.UNSAFE_PATH),
    ],
)
def test_classifies_git_entry_and_path_failures(
    tmp_path: Path,
    entry: TrackedFile,
    reason: SkipReason,
) -> None:
    decisions = discover(tmp_path, [entry])

    assert decisions == [SkippedFile(entry.relative_path, reason)]


def test_skips_working_tree_symlink_and_symlinked_parent(tmp_path: Path) -> None:
    target = write(tmp_path, "target.py", b"print('target')\n")
    (tmp_path / "link.py").symlink_to(target)
    outside = tmp_path / "outside"
    outside.mkdir()
    write(outside, "nested.py", b"print('outside')\n")
    (tmp_path / "linked-directory").symlink_to(outside, target_is_directory=True)

    decisions = discover(
        tmp_path,
        [tracked("link.py"), tracked("linked-directory/nested.py")],
    )

    assert decisions == [
        SkippedFile(PurePosixPath("link.py"), SkipReason.SYMLINK),
        SkippedFile(
            PurePosixPath("linked-directory/nested.py"),
            SkipReason.SYMLINK,
        ),
    ]


