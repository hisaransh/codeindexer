def test_enforces_inclusive_file_size_limit(tmp_path: Path) -> None:
    write(tmp_path, "accepted.txt", b"a" * 10)
    write(tmp_path, "oversized.txt", b"a" * 11)

    decisions = discover(
        tmp_path,
        [tracked("accepted.txt"), tracked("oversized.txt")],
        max_file_bytes=10,
    )

    assert decisions == [
        DiscoveredFile(PurePosixPath("accepted.txt"), "a" * 10, 10),
        SkippedFile(PurePosixPath("oversized.txt"), SkipReason.OVERSIZED),
    ]


